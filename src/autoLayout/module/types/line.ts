/**
 * **무엇을 나르나** — 모듈 하나가 안팎으로 주고받는 I/O 줄([IoLine]), 그 줄의 배정
 * ([PlannedLine]), 그 줄이 나르는 양([SupplyCapacity]), 그리고 그 양을 싣는 물리 벨트 한 줄([Link]).
 *
 * **여기엔 실행되는 것이 없다** — 타입뿐이다. 그래서 계획·배정·방출이 다 같은 타입을 쓰면서도
 * 서로를 import 하지 않는다. 관심사 폴더 `module/` 의 타입은 이 폴더의 세 파일이 나눠 든다
 * — 가르는 기준은 읽는 사람의 질문이다(나르나 · [seat](./seat.ts) 앉나 · [module](./module.ts) 받고 내나).
 *
 * > **내력.** 줄의 타입은 `clusterPortPlanner.ts` 에 있다가(2026-09-02 분리) `planner/module/ioLine.ts`
 * > 로, [Link] 는 `module/link.ts` 에 있다가 2026-09-13 여기로 왔다(계획 구조-2축 · 2 Step 1).
 * > 계획 계층에 두면 `module/` 과 `execution/` 이 타입을 가지러 위로 올라가야 했다.
 *
 * ## ClusterBeltDepth 규약 (머신 면에서 바깥으로 N칸 — 용어: docs/용어사전.md §D)
 *  - 0칸 = 머신 자신의 가장자리(인서터가 떨구는 목적지).
 *  - 1칸 = 좌석 줄. 인서터가 여기 앉는다. 유체 파이프는 머신 fluid_box 에 닿아야 하므로
 *    **여기 온다**(팔이 없어 머신에 닿아야 한다).
 *  - 2..(1+최대 reach)칸 = [ClusterBelt] 자리. reach `r` 인서터가 좌석(1칸)에 앉아 `1+r`칸의
 *    벨트를 집는다. 그래서 한 면의 깊이 수 = **고른 인서터들의 서로 다른 reach 값 개수**
 *    (하드코딩 아님 — 그 수를 세는 곳은 `linkPlanner.clusterBeltDepthsOf` 다).
 */

/** 컬럼의 좌/우 면. */
export type PortSide = "W" | "E";

/**
 * 배정 결과가 가리킬 수 있는 면 — 좌/우(W/E) + **노출된 끝면(N/S)**.
 * N/S 는 count=1(퇴화 기둥)의 raw 입력 전용 완화다: 기둥에서 N/S 깊이는 끝 머신
 * 1대만 서빙 가능해 일반화가 안 되지만, 머신이 1대면 4면이 전부 동등하다. 노출
 * 여부(열의 끝 + 그 방향 전역 마진)는 호출자(packModuleTree)가 판정해 넘긴다.
 */
export type PlannedSide = PortSide | "N" | "S";

/** I/O 줄의 운반체 종류 — 아이템=belt(인서터 탭), 유체=pipe(스파인, 인서터 없음). */
export type LineKind = "belt" | "pipe";

/** 배정 대상 — 레시피의 한 I/O 품목. */
export interface IoLine {
  /** 품목 이름(아이템/유체). */
  name: string;
  kind: LineKind;
  role: "input" | "output";
  /**
   * craft당 수량 = 운반량(throughput) 프록시. 한 클러스터 내 모든 라인은 같은 craft
   * 속도라 amount 비율이 곧 throughput 비율 → depth 배정 기준. 미지정=0.
   */
  amount?: number;
  /**
   * 외부 라인(트리 안 생산자 없음 → 무한상자로 살아남아 perimeter 로 나가야 함).
   * true 인 입력만 노출 N/S 슬롯(`nsFaces`)을 쓸 수 있다 — 내부 간선(납품 경로로 대체될
   * 라인)은 납품 경로 기하 불변을 위해 W/E 에 남긴다. packModuleTree 가 childFed 판정으로
   * 채운다. 미지정=내부 취급.
   */
  external?: boolean;
}

/**
 * **한 I/O 줄의 배정 하나** — 줄 하나가 배정을 **여러 개** 가질 수 있다.
 *
 * 수요가 벨트 한 줄을 넘으면 [determineBeltCount] 가 줄 수를 늘리고, 그러면 이 줄은
 * 배정을 그 수만큼 갖는다(각각 자기 면·자기 벨트·자기 포트). 옛 모델은 "줄 하나 = 배정
 * 하나" 였고, 그래서 벨트 한 줄을 넘는 수요를 **거절**할 수밖에 없었다.
 */
export interface PlannedLine {
  line: IoLine;
  side: PlannedSide;
  /**
   * [ClusterBeltDepth](../../../../../docs/용어사전.md) — 머신 면에서 바깥 칸 거리.
   * pipe=1, 벨트=`1+reach`(케이스 B 면 `2+reach`).
   */
  clusterBeltDepth: number;
  /**
   * 이 줄을 집는 인서터의 **reach**. reach `r` 인서터가 좌석에 앉아 `1+r`칸(케이스 B 면
   * `2+r`칸)의 벨트를 집는다. pipe 는 인서터가 없어 undefined.
   */
  reach?: number;
  /**
   * 이 배정이 까는 벨트의 prototype. [determineBeltCount] 가 티어를 고른다(빠른 것부터,
   * 나머지는 그걸 감당하는 가장 싼 것). 미지정이면 호출부의 기본 벨트.
   */
  beltEntityName?: string;
  /**
   * **[requiredInserterCount](../../../../../docs/용어사전.md#requiredinsertercount)** — 머신 한
   * 대의 이 줄을 먹이는 데 필요한 인서터 팔의 개수. **공급 방식과 무관한 물리량**이다
   * (`ceil(머신당 수요 ÷ 인서터 하나 처리량)`) — 탭이면 그 팔들이 같은 [ClusterBelt] 에서
   * 집고([Parallel Inserting](../../../../../docs/용어사전.md#parallel-inserting)), 다이렉트면
   * 각자 자기 상자에서 집는다. 팔 **개수** 자체는 어느 쪽이든 같다.
   *
   * [insertingPlanner] 가 [SupplyCapacity] 로 **두 모드 모두에** 채운다. 미지정 = 수량을
   * 모른다(판정 보류 → 소비처가 1로 본다). `planClusterPorts` 자체는 채우지 않는다(용량을
   * 안 본다).
   */
  requiredInserterCount?: number;
}

/** 벨트·인서터가 감당할 수 있는 양(items/sec). 미지정 항목은 무제한으로 본다. */
export interface SupplyCapacity {
  /** 벨트 한 줄의 초당 운반량. 이걸 넘는 품목은 한 줄로 못 나른다. */
  beltCapacity?: number;
  /**
   * 품목별 **클러스터 전체** 초당 수요/산출(items/sec). 키 = `${role}:${name}`.
   * 미지정이면 [requiredInserterCount] 가 `undefined` 를 낸다 — 없는 숫자를 지어내지 않는다.
   */
  lineRates?: Map<string, number>;
}

/**
 * **벨트 하나** — 이 클러스터의 머신들이 상대와 주고받는 물리 벨트 하나 = 포트 한 쌍.
 *
 * ## 왜 목적지마다 벨트를 따로 내나
 * **v1 은 링크 하나가 곧 그룹 하나다**(2026-07-22). 여러 목적지를 한 벨트에 묶으면 그 벨트가
 * 부모 머신 여럿을 **관통**해야 하고, 그러려면 그 머신들이 **붙어 있어야** 한다
 * ([[용어사전#ColumnCluster]]). 채널 트랙 하나를 아끼려고 클러스터 형태 전체를 저당 잡히는
 * 거래라 v1 에서는 안 한다.
 *
 * `from`/`to` 가 Map 인 이유: 병합을 되살리거나(여러 목적지) 외부 줄을 담을 때(전 머신)
 * 자료 구조를 다시 안 바꾸려는 것이다. 내부 링크 v1 에서는 양쪽 다 항목 하나씩이다.
 */
export interface Link {
  /**
   * **지정 짝의 토큰 — 비어 있는 것이 뜻을 갖는다.**
   *
   * ```
   * 있다   이 포트는 형제 모듈의 **저** 포트와 이어져야 한다.  바꿔 끼우면 틀린다
   * 없다   같은 품목이면 **아무거나** 이어도 된다(교환 가능)
   * ```
   *
   * [pairDeliveryPorts] 가 이 유무로 갈린다 — 있으면 토큰 조회, 없으면 위치-zip. 그래서
   * *"식별자가 있으면 편하겠지"* 로 채우면 **알고리즘의 갈래가 조용히 바뀐다**(2026-08-17 실측:
   * 채운 줄이 납품 경로를 통째로 잃었다).
   *
   * **채우는 곳은 [makeLinkId] 하나뿐이다.** 지정이 존재하는 조건은 *"외부냐 내부냐"* 가 아니라
   * **"[allocateFlows] 가 머신 단위로 배정했나"** 다 — 배정이 없으면 지킬 것도 없으므로
   * 교환 가능이고, 그때는 비워 두는 것이 **정답**이지 정보 부족이 아니다.
   *
   * 값 자체는 **불투명 토큰**이다. 간선의 양끝(자식·부모 노드 id)을 아는 호출자
   * (`planner/modulePacking`)가 채우고, 이 폴더는 **파싱하지 않는다**.
   */
  id?: string;
  /** 운반 품목. */
  item: string;
  /**
   * 이 벨트에 물건을 **내놓는** 머신 → 그 머신이 쓰는 팔 수.
   * **비어 있으면 물건이 모듈 밖에서 온다**(= 외부 입력 줄: 원료).
   */
  from: Map<number, number>;
  /**
   * 이 벨트에서 물건을 **받는** 머신 → 그 머신이 쓰는 팔 수.
   * **비어 있으면 물건이 모듈 밖으로 나간다**(= 외부 출력 줄: 완제품).
   */
  to: Map<number, number>;
  /**
   * **적재 목록 — 이 줄이 무엇을 얼마나 싣고 있나**(2026-08-23). 모르면 `undefined`
   * (지어내지 않는다).
   *
   * 항목 하나가 [Flow](= 흐름) 하나의 **이 줄이 맡은 몫**이다. 흐름과 벨트 줄은
   * M:N 이라(한 줄이 흐름 여럿을 싣고 = 트렁크, 한 머신이 줄 여럿을 쓰고 = split belt)
   * 이 목록이 그 대응을 담는 **유일한 자리**다.
   *
   * **`from`/`to` 는 여기서 유도된다.** 두 명단만 들던 시절엔 `from={0:2}, to={1:1,2:1}`
   * 에서 *0번 자식이 1번·2번에게 각각 얼마씩* 인지를 표현하지 못했고, 그래서 [machine-link]
   * 가 `toMachine` 을 *"물류 계약이 아니라 장부"* 라고 방어해야 했다. 적재 목록이 있으면
   * **계약**이다 — 다만 *"인서터는 앞에 물건이 있으면 무조건 내린다"* 는 물리는 그대로라,
   * 한 줄에 부모가 여럿이면 **그 줄 안에서의 분배는 여전히 물리가 정한다**. 계약이 보장하는
   * 것은 *"그 줄에 이만큼이 실려 그 행을 지난다"* 까지다.
   *
   * 불변식: `Σ rate ≤ 그 벨트의 처리량`([groupRate] 로 센다). 팔 수로는 못 센다 —
   * `팔 수 × 팔 처리량` 은 **올림된 용량**이라 언제나 실제보다 크고, 그래서 진단이 멀쩡한
   * 줄을 "포화" 라고 거짓 경고한다.
   */
  carries?: ReadonlyArray<LinkCarry>;
  /**
   * 이 줄에 깔 벨트 prototype — [determineBeltCount] 가 **양에서** 고른 티어.
   *
   * 모르면 `undefined` 이고, 그때 방출기가 [ModuleInput.beltEntityName](기본 벨트)로 깐다.
   * **실으려는 양을 정한 곳과 깔 벨트를 고르는 곳이 갈리면 용량이 거짓이 된다** — 접기는
   * 90/s 짜리로 세 놓고 방출이 15/s 짜리를 깔면 그 줄은 조용히 굶는다(2026-08-22 관측).
   */
  beltEntityName?: string;
  /**
   * **짝이 있는 쪽 끝** — 이 줄의 포트가 기둥 어느 끝에 서야 짝과 **안 교차하나**.
   * `from` 은 자식 쪽 끝, `to` 는 부모 쪽 끝(둘은 서로 반대쪽을 본다).
   *
   * **거리가 아니라 교차를 노린다.** *"가장 가까운 끝"* 은 두 기둥의 **모서리**를 알아야 하고,
   * 모서리는 높이를, 높이는 `generateModule` 을 부른다 — 그 목표를 지키는 한 되먹임을 못 연다.
   * 반면 *"누가 위에 있나"* 는 **형제 순서**만으로 알고, 그건 트리가 안다.
   * 그리고 채널이 값을 매기는 것도 교차 쪽이다(교차하면 두 줄이 트랙을 못 나눠 쓴다).
   *
   * `undefined` = 모른다(형제가 하나뿐) → 배정이 오늘처럼 선착순으로 고른다.
   * **`id` 와 같은 규칙으로 산다**: 간선의 양끝을 아는 위층(`planner/modulePacking`)이
   * 채우고, 이 폴더는 만들지 않는다.
   */
  end?: { from: "N" | "S"; to: "N" | "S" };
  /**
   * **이 줄이 남과 물리 벨트를 나눠 쓰나** — 같은 `lineId` 를 가진 줄과 **한 벨트의
   * 좌/우 두 레인**에 각각 실린다([belt-lane-semantics](../../../../docs/factorio/belt-lane-semantics.md)).
   * `undefined` = 자기 벨트를 통째로 쓴다(오늘의 전부).
   *
   * ## 왜 [Link] 를 합치지 않고 둘로 두나
   * [carries] 의 불변식은 *"실린 총량 ≤ 그 벨트의 처리량"* 이다. 레인 공유는 그 불변식을
   * **깨는 게 아니라 상수만 바꾼다** — `처리량` → `처리량 ÷ 2`([laneThroughput]). 반대로
   * `item` 을 배열로 만들면 그 불변식을 줄당/레인당 **둘로 갈라야** 하고, `item` 이 하나라는
   * 전제가 박힌 `armsAt`·`IoLine`·포트 상자 `content`·`pairDeliveryPorts` 가 전부 따라 바뀐다.
   *
   * ## `side` 는 취향이 아니라 **합류 기하가 정한다**
   * 사이드로드는 레인을 접는다 — 옆에서 들어온 벨트의 두 레인 전부가 **자기가 닿은 쪽**
   * 레인 하나로 들어간다. 그래서 *"그 지류가 합류 칸의 어느 옆면에서 왔나"* 가 곧 레인이고,
   * 이름은 게임 API 그대로다(`LuaEntity::pickup_from_left_lane`) — **진행 방향 기준** 좌/우.
   *
   * ## 좌/우 **어느 레인인지는 여기 없다**
   * 그건 이 층이 답할 수 없다 — 사이드로드가 접는 레인은 *"그 지류가 합류 칸의 어느
   * 옆면에서 왔나"* 이고, 그 답은 **합류 기하**(채널의 세로 주행이 위에서 오나 아래서
   * 오나)가 정한다. 그리고 아무도 안 물어본다: 집는 팔은 **필터**로 품목을 고르지
   * 레인을 고르지 않는다([belt-lane-semantics] ②). 그래서 필드가 하나면 족하다.
   *
   * 채우는 곳은 [shareLanes] 하나다. 방출기는 이 값이 같은 둘을 **한 번만** 깐다.
   */
  sharedLineId?: string;
}

/** 벨트 한 줄의 좌/우 레인 — **진행 방향 기준**(게임 런타임 API 와 같은 이름). */
export type LaneSide = "left" | "right";

/** [Link.carries] 의 항목 — 흐름 하나가 이 줄에 실은 몫. */
export interface LinkCarry {
  /** 내놓는 머신. **없으면 밖에서 온다**(원료). */
  from?: number;
  /** 받는 머신. **없으면 밖으로 나간다**(완제품). */
  to?: number;
  /** 이 줄이 맡은 초당 개수. */
  rate: number;
}
